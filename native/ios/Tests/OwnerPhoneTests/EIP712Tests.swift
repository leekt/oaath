/**
 Cross-runtime and negative proofs for the reject-only Swift EIP-712 primitive.

 The accepted vectors live once under the protocol package and are verified
 there against viem. Swift parses that trusted fixture, then independently
 captures and hashes each canonical value with CryptoSwift Keccak-256.

 @author taek <leekt216@gmail.com>
 */
import Foundation
import XCTest
@testable import OwnerPhone

final class EIP712Tests: XCTestCase {
    func testSharedProtocolVectorsAndEveryMutationMatchExactly() throws {
        let fixture = try sharedFixture()
        XCTAssertEqual(fixture["version"] as? String, "oaath.eip712-hash-vectors/v1")
        let vectors = try XCTUnwrap(fixture["vectors"] as? [Any])
        XCTAssertEqual(vectors.count, 3)

        var mutationCount = 0
        for rawVector in vectors {
            let vector = try XCTUnwrap(rawVector as? [String: Any])
            let name = try XCTUnwrap(vector["name"] as? String)
            let typedData = try XCTUnwrap(vector["typedData"])
            let expected = try XCTUnwrap(vector["expectedDigest"] as? String)
            let digest = try deriveEIP712Digest(jsonValue: typedData)
            XCTAssertEqual(digest.canonicalHex, expected, name)
            XCTAssertEqual(
                try compareEIP712Digest(jsonValue: typedData, expectedDigest: expected),
                .matches(digest),
                name
            )

            for rawMutation in try XCTUnwrap(vector["mutations"] as? [Any]) {
                let mutation = try XCTUnwrap(rawMutation as? [String: Any])
                let mutated = try mutableJSONClone(typedData)
                try setJSONPointer(
                    try XCTUnwrap(mutation["pointer"] as? String),
                    in: mutated,
                    to: try XCTUnwrap(mutation["value"])
                )
                let mutationName = "\(name)/\(try XCTUnwrap(mutation["name"] as? String))"
                XCTAssertEqual(
                    try deriveEIP712Digest(jsonValue: mutated).canonicalHex,
                    try XCTUnwrap(mutation["expectedDigest"] as? String),
                    mutationName
                )
                mutationCount += 1
            }
        }
        XCTAssertEqual(mutationCount, 7)
    }

    func testOfficialMailVectorIsAnEthereumKeccakSanityCheck() throws {
        let fixture = try sharedFixture()
        let vectors = try XCTUnwrap(fixture["vectors"] as? [Any])
        let mail = try XCTUnwrap(vectors.first as? [String: Any])
        // SHA3-256 would not produce the official EIP-712 result. This exact
        // vector therefore guards CryptoSwift's Ethereum `.keccak256` variant.
        XCTAssertEqual(
            try deriveEIP712Digest(jsonValue: try XCTUnwrap(mail["typedData"])).canonicalHex,
            "0xbe609aee343fb3c4b28e1df9e632fca64fcfaede20f02e86244efddf30957bd2"
        )
    }

    func testEverySupportedFixedBytesAndIntegerWidthCapturesAndHashes() throws {
        for width in 1...32 {
            let value = "0x" + String(repeating: "ab", count: width)
            XCTAssertNoThrow(
                try deriveEIP712Digest(jsonValue: atomicTypedData(type: "bytes\(width)", value: value)),
                "bytes\(width)"
            )
        }
        for width in stride(from: 8, through: 256, by: 8) {
            XCTAssertNoThrow(
                try deriveEIP712Digest(jsonValue: atomicTypedData(type: "uint\(width)", value: "0")),
                "uint\(width)"
            )
            XCTAssertNoThrow(
                try deriveEIP712Digest(jsonValue: atomicTypedData(type: "int\(width)", value: "0")),
                "int\(width)"
            )
        }
    }

    func testCustomDependenciesAreAppendedInLexicographicOrder() throws {
        let typedData: [String: Any] = [
            "types": [
                "EIP712Domain": [["name": "chainId", "type": "uint256"]],
                "Zed": [["name": "value", "type": "uint8"]],
                "Alpha": [["name": "value", "type": "string"]],
                "Envelope": [
                    ["name": "z", "type": "Zed"],
                    ["name": "a", "type": "Alpha"]
                ]
            ],
            "primaryType": "Envelope",
            "domain": ["chainId": "1"],
            "message": [
                "z": ["value": "7"],
                "a": ["value": "sorted"]
            ]
        ]
        // Independently generated by viem from
        // Envelope(...)Alpha(...)Zed(...), regardless of dictionary order.
        XCTAssertEqual(
            try deriveEIP712Digest(jsonValue: typedData).canonicalHex,
            "0x6b92b63f2ad8789b3b3883019e4831a886e83e4529ebf3803530081d07efd7c4"
        )
    }

    func testNoncanonicalBuiltinLookalikesRemainValidCustomPrimaryTypes() throws {
        // The protocol parser treats these as custom struct identifiers when
        // they are primary types; only their use as field types is malformed.
        // Expected digests come from its viem-backed hash owner.
        let expected: [String: String] = [
            "bytes01": "0x4155c40d14764d9780e579fbd4554d6cfc2e049f03d99891ee476b795072d792",
            "uint08": "0x5c4c19850495bb71854dde11ba4a005e57002a9138606a091a425a55e2728397",
            "int08": "0x891231d7f70ec6ec639259195769c834b6bdbfad322b511de489785f0e537944"
        ]
        for (name, digest) in expected {
            let typedData: [String: Any] = [
                "types": [
                    "EIP712Domain": [["name": "chainId", "type": "uint256"]],
                    name: [["name": "value", "type": "uint8"]]
                ],
                "primaryType": name,
                "domain": ["chainId": "1"],
                "message": ["value": "7"]
            ]
            XCTAssertEqual(
                try deriveEIP712Digest(jsonValue: typedData).canonicalHex,
                digest,
                name
            )
        }
    }

    func testCompleteCanonicalDomainIncludingSaltHashesExactly() throws {
        let typedData: [String: Any] = [
            "types": [
                "EIP712Domain": [
                    ["name": "name", "type": "string"],
                    ["name": "version", "type": "string"],
                    ["name": "chainId", "type": "uint256"],
                    ["name": "verifyingContract", "type": "address"],
                    ["name": "salt", "type": "bytes32"]
                ],
                "Payload": [["name": "value", "type": "bool"]]
            ],
            "primaryType": "Payload",
            "domain": [
                "name": "All Domain",
                "version": "1",
